
// Flutter Project Structure :-

// When We Create A New Flutter Project,
// Flutter Gives Us Some Files & Folders By Default.
//
// Each File & Folder Has Its Own Purpose.
// Let's Understand The Important Ones.

// MAIN FOLDERS :-
//
// lib       -> Contains The Main Dart Code Of Our App.
// android   -> Contains Android-Specific Project Files.
// ios       -> Contains iOS-Specific Project Files.
// web       -> Contains Web-Specific Project Files.
// test      -> Used To Write Tests For Our App.
// assets    -> Used To Store Images, Fonts & Other Files.
//
// The `lib` Folder Is Where We Mostly Write Our Flutter Code.

// IMPORTANT FILES :-

// main.dart
// This Is The Entry Point Of Our Flutter App.
// Our App Starts Running From This File.

// pubspec.yaml
// This File Contains Project Information,
// Dependencies, Assets & Fonts.
//
// We Use It To Add Packages & Configure Our Project.

// analysis_options.yaml
// This File Contains Rules For Dart Code Analysis.
// It Helps Us Keep Our Code Clean & Consistent.

// README.md
// This File Contains Information About Our Project.
// It Usually Explains What The App Does & How To Use It.

// UNDERSTANDING THE `lib` FOLDER :-

// The `lib` Folder Is The Main Place
// Where We Organize Our Flutter App Code.
//
// For Small Projects, We Can Keep Our Code Simple.
// As The App Grows, We Can Create More Folders
// To Keep Everything Organized.

// A SIMPLE PROJECT STRUCTURE :-

// lib/
//   main.dart
//   screens/
//   widgets/
//   models/

// main.dart   -> Starts Our App.
// screens/    -> Contains Different App Screens.
// widgets/    -> Contains Reusable Widgets.
// models/     -> Contains Data Models.

// WHY PROJECT STRUCTURE MATTERS :-

// A Good Project Structure Makes Our Code
// Easier To Read, Understand & Maintain.
//
// It Also Helps Us Find Files Easily
// When Our App Becomes Bigger.

// A SIMPLE RULE :-

// Use `lib` To Write Your Main Flutter Code.
// Use `main.dart` As Your App Entry Point.
// Use `pubspec.yaml` To Manage Packages & Assets.
// Keep Your Files Organized As Your App Grows.
